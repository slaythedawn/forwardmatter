/**
 * Generates the Forward Matter mark from the hero animation's own brain.
 *
 * `brain-field.js` already defines the silhouette as a union of ellipses with
 * the lateral fissure and the cerebellar notch carved back out. Reading it here
 * rather than redrawing it means the logo and the particle field can never
 * drift apart: change the animation's brain and this regenerates to match.
 *
 * The mark is a halftone of that field. Dot radius follows depth inside the
 * silhouette, which is what lets a regular grid describe a curve — masking a
 * uniform grid with the same outline reads as a rectangle of dots, because the
 * eye follows the rows and ignores the envelope. Dots over the frontal lobe are
 * drawn resolved; the rest sit back as ambient field.
 *
 * Run: npm run build:brand
 */
import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const source = readFileSync(join(ROOT, "public/vendor/brain-field.js"), "utf8");
const literal = (name) => {
  const match = source.match(new RegExp(`const ${name} = (\\[[\\s\\S]*?\\n  \\];)`));
  if (!match) throw new Error(`${name} not found in brain-field.js`);
  return JSON.parse(match[1].replace(/\/\/[^\n]*/g, "").replace(/,(\s*])/g, "$1").replace(/;$/, ""));
};
const LOBES = literal("LOBES");
const CARVE = literal("CARVE");

/* Normalised space, matching the animation: x right, y up. The mark is
   mirrored on x so the profile faces forward. */
const X0 = -1.05, X1 = 1.05, Y0 = -0.85, Y1 = 0.85;

function depth(x, y) {
  let best = -1;
  for (const [cx, cy, rx, ry] of LOBES) {
    const v = 1 - Math.hypot((x - cx) / rx, (y - cy) / ry);
    if (v > best) best = v;
  }
  if (best <= 0) return best;
  for (const [cx, cy, rx, ry] of CARVE) {
    if (Math.hypot((x - cx) / rx, (y - cy) / ry) < 1) return -1;
  }
  return best;
}

/* How resolved a dot is: 1 over the frontal lobe, falling off to 0. The frontal
   lobe is the part of a brain that does anticipation, and it sits at the front
   of a profile that is already facing forward. */
function resolved(x, y) {
  const [fx, fy, frx, fry] = LOBES[0];
  const [sx, sy, srx, sry] = LOBES[1];
  const a = 1 - Math.hypot((x - fx) / (frx * 1.25), (y - fy) / (fry * 1.25));
  const b = 1 - Math.hypot((x - sx) / (srx * 0.95), (y - sy) / (sry * 0.95));
  return Math.min(1, Math.max(0, Math.pow(Math.max(0, a, b) / 0.6, 0.9)));
}

const STEP = 10;
const round = (n) => Math.round(n * 100) / 100;

function cut({ cols, rows, pad, rBase, rGain }) {
  const dots = [];
  for (let row = 0; row < rows; row++) {
    for (let col = 0; col < cols; col++) {
      const x = -(X0 + ((col + 0.5) / cols) * (X1 - X0));
      const y = Y1 - ((row + 0.5) / rows) * (Y1 - Y0);
      const d = depth(x, y);
      if (d <= 0.02) continue;
      const t = resolved(x, y);
      dots.push({
        col, row,
        r: (rBase + rGain * Math.pow(Math.min(d / 0.85, 1), 0.7)) * (1 + 0.42 * t),
        o: 0.28 + 0.72 * t,
      });
    }
  }
  const cols_ = dots.map((d) => d.col), rows_ = dots.map((d) => d.row);
  const c0 = Math.min(...cols_), r0 = Math.min(...rows_);
  const w = (Math.max(...cols_) - c0) * STEP + pad * 2;
  const h = (Math.max(...rows_) - r0) * STEP + pad * 2;
  return {
    viewBox: `0 0 ${round(w)} ${round(h)}`,
    width: round(w),
    height: round(h),
    dots: dots.map((d) => [
      round((d.col - c0) * STEP + pad),
      round((d.row - r0) * STEP + pad),
      round(d.r),
      round(d.o),
    ]),
  };
}

const CUTS = {
  // 64px and up. Below that the dots stop resolving and the brain goes with them.
  full: cut({ cols: 19, rows: 15, pad: 5, rBase: 0.8, rGain: 2.6 }),
  // 40 to 64px: the header.
  mid: cut({ cols: 15, rows: 12, pad: 5, rBase: 1.1, rGain: 3.0 }),
  // Under 40px, where it reads as a dense cluster beside a sparse one.
  small: cut({ cols: 11, rows: 9, pad: 5.5, rBase: 1.3, rGain: 3.1 }),
};

const svg = (c, fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${c.viewBox}">` +
  `<g fill="${fill}">` +
  c.dots.map(([x, y, r, o]) => `<circle cx="${x}" cy="${y}" r="${r}" fill-opacity="${o}"/>`).join("") +
  `</g></svg>`;

// ---- component data -------------------------------------------------------
const ts =
  `/* Generated by scripts/build-brand.mjs from public/vendor/brain-field.js.\n` +
  `   Do not edit by hand: run \`npm run build:brand\` instead. */\n\n` +
  `export type BrandCut = { viewBox: string; dots: [number, number, number, number][] };\n\n` +
  Object.entries(CUTS)
    .map(([name, c]) =>
      `export const ${name}: BrandCut = {\n` +
      `  viewBox: "${c.viewBox}",\n` +
      `  dots: [\n` +
      c.dots.map((d) => `    [${d.join(", ")}],`).join("\n") +
      `\n  ],\n};\n`)
    .join("\n");
writeFileSync(join(ROOT, "components/brandMarkData.ts"), ts);

// ---- icons ----------------------------------------------------------------
const INK = "#242e3a";
const LIGHT = "#eef0f3";

/* iOS composites any transparency onto black, so every raster icon ships
   flattened on the dark panel colour rather than cut out. */
async function raster(file, size, cutName = "small") {
  const c = CUTS[cutName];
  const scale = Math.min(size * 0.78 / c.width, size * 0.78 / c.height);
  const inner = Math.round(c.height * scale);
  const buf = await sharp(Buffer.from(svg(c, LIGHT)), { density: 1600 })
    .resize({ height: Math.max(inner, 8) })
    .png()
    .toBuffer();
  const meta = await sharp(buf).metadata();
  await sharp({
    create: { width: size, height: size, channels: 4, background: INK },
  })
    .composite([{
      input: buf,
      left: Math.round((size - meta.width) / 2),
      top: Math.round((size - meta.height) / 2),
    }])
    .png()
    .toFile(join(ROOT, file));
}

mkdirSync(join(ROOT, "public"), { recursive: true });
writeFileSync(join(ROOT, "app/icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${CUTS.small.viewBox}" width="${CUTS.small.width}" height="${CUTS.small.height}">` +
  svg(CUTS.small, "#242d38").replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "") +
  `</svg>`);

await raster("app/apple-icon.png", 180);
await raster("public/icon-192.png", 192);
await raster("public/icon-512.png", 512, "mid");

// favicon.ico, with a PNG payload — browsers request it whatever else is set.
const ico = await sharp(join(ROOT, "public/icon-192.png")).resize(32, 32).png().toBuffer();
const header = Buffer.alloc(22);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header.writeUInt8(32, 6); header.writeUInt8(32, 7); header.writeUInt8(0, 8);
header.writeUInt8(0, 9); header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(ico.length, 14); header.writeUInt32LE(22, 18);
writeFileSync(join(ROOT, "app/favicon.ico"), Buffer.concat([header, ico]));

